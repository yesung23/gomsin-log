import { describe, it, expect } from 'vitest';
import { groupIntoRuns, describeRuns } from '@/lib/dateRuns';

describe('고른 날들을 연속 구간으로 자른다', () => {
  it('붙어 있는 날들은 한 건이 된다', () => {
    expect(groupIntoRuns(['2026-08-14', '2026-08-15', '2026-08-16']))
      .toEqual([{ start: '2026-08-14', end: '2026-08-16' }]);
  });

  it('흩어진 날들은 각각 하루짜리가 된다', () => {
    expect(groupIntoRuns(['2026-08-14', '2026-08-20', '2026-08-27']))
      .toEqual([{ start: '2026-08-14' }, { start: '2026-08-20' }, { start: '2026-08-27' }]);
  });

  it('붙은 것과 흩어진 것이 섞이면 섞인 대로 나뉜다', () => {
    expect(groupIntoRuns(['2026-08-20', '2026-08-14', '2026-08-15']))
      .toEqual([{ start: '2026-08-14', end: '2026-08-15' }, { start: '2026-08-20' }]);
  });

  /*
    하루짜리에 `end` 를 주지 않는 것이 이 함수의 계약이다. 같은 날을 종료일로 적으면
    하루짜리가 기간 일정처럼 읽히고 기존 데이터와 모양이 달라진다.
  */
  it('하루짜리는 종료일을 갖지 않는다', () => {
    const [run] = groupIntoRuns(['2026-08-14']);
    expect(run).toEqual({ start: '2026-08-14' });
    expect('end' in run).toBe(false);
  });

  it('순서가 뒤죽박죽이어도, 같은 날을 두 번 골라도 같은 답이다', () => {
    expect(groupIntoRuns(['2026-08-16', '2026-08-14', '2026-08-15', '2026-08-14']))
      .toEqual(groupIntoRuns(['2026-08-14', '2026-08-15', '2026-08-16']));
  });

  /* 월과 해를 넘어가도 연속이다 -- 문자열 비교로는 알 수 없는 것이다. */
  it('달을 넘어가는 연속을 끊지 않는다', () => {
    expect(groupIntoRuns(['2026-08-31', '2026-09-01']))
      .toEqual([{ start: '2026-08-31', end: '2026-09-01' }]);
  });

  it('해를 넘어가는 연속도 끊지 않는다', () => {
    expect(groupIntoRuns(['2026-12-31', '2027-01-01']))
      .toEqual([{ start: '2026-12-31', end: '2027-01-01' }]);
  });

  it('아무것도 안 골랐으면 아무 구간도 없다', () => {
    expect(groupIntoRuns([])).toEqual([]);
  });
});

describe('고른 것을 저장하기 전에 말해 준다', () => {
  it('하루', () => {
    expect(describeRuns(['2026-08-14'])).toBe('08-14 하루');
  });

  it('연속이면 며칠인지', () => {
    expect(describeRuns(['2026-08-14', '2026-08-15', '2026-08-16']))
      .toBe('08-14 – 08-16 · 3일');
  });

  /*
    흩어진 날을 고른 사람은 그것이 **일정 여러 건**이 된다는 것을 저장 전에 알아야 한다.
    저장하고 나서 격자에서 발견하면 그때는 지우는 일이 남는다.
  */
  it('흩어졌으면 몇 건이 되는지까지 말한다', () => {
    expect(describeRuns(['2026-08-14', '2026-08-20', '2026-08-27']))
      .toBe('3일 고름 · 일정 3건');
  });

  it('섞였으면 날 수와 건수가 다르다는 것이 그대로 보인다', () => {
    expect(describeRuns(['2026-08-14', '2026-08-15', '2026-08-20']))
      .toBe('3일 고름 · 일정 2건');
  });

  it('아무것도 안 골랐으면 고르라고 한다', () => {
    expect(describeRuns([])).toBe('날짜를 골라 주세요');
  });
});
